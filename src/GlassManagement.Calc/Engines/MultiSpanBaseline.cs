    public static IReadOnlyList<MultiSpanBaseline> All { get; } = new[] { Sample1, Sample2 };

    /// <summary>按几何匹配基线；不匹配返回 null。</summary>
    public static MultiSpanBaseline? Match(int spans, double aMm, double lMm)
        => All.FirstOrDefault(b => b.Matches(spans, aMm, lMm));

    /// <summary>按样本 ID 取基线。</summary>
    public static MultiSpanBaseline? ById(string id)
        => All.FirstOrDefault(b => b.SampleId == id);
