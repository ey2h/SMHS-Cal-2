/// <summary>
/// V31 实测基线样本（多跨铰接连续静定梁「预演」输出）。
///
/// 来源（本地落盘）：
///   local-data/recon/multispan_presult_v31.json            样本1
///   local-data/recon/multispan_presult_v31_sample2.json    样本2
/// 抓取方式：AutomationElement.Current.Name 读取 VB6 RichTextWndClass 全文。
///
/// 用途：复刻界面把「实测原文」作为黄金样本，用户改参数后可逐字符对照；
///       参数与某个基线完全一致时，预演输出直接采用该基线原文（格式零误差）。
/// </summary>
public sealed class MultiSpanBaseline
{
    public sealed record CheckRow(
        string Group,        // 抗弯强度 / 抗剪强度 / 折算强度 / 支座处抗弯强度 / ...
        string Location,     // 第1跨 / 第2跨立柱支座处 / ...
        double Computed,
        double Allowable,
        string Unit,         // MPa / mm
        string RawLabel,     // 原文首行，如"第1跨立柱抗弯强度计算值"
        string RawAllowLabel // 原文第二行，如"立柱型材抗弯强度设计值"
    );

    public string SampleId { get; init; } = "";
    public string Note { get; init; } = "";
    public int TotalSpans { get; init; }
    public double SegmentAMm { get; init; }   // 跨长 A（支座段）
    public double SegmentLMm { get; init; }   // 跨长 L（计算跨度）
    public double WindKpa { get; init; }
    public string Material { get; init; } = "";
    public string Standard { get; init; } = "";
    public IReadOnlyList<CheckRow> Checks { get; init; } = Array.Empty<CheckRow>();
    /// <summary>V31 预演原文（含 42 星号分隔线与「为为」笔误），逐字符保真。</summary>
    public string RawText { get; init; } = "";

    /// <summary>几何是否与当前输入完全一致（跨数 + A + L 三者都相等）。</summary>
    public bool Matches(int spans, double aMm, double lMm)
        => spans == TotalSpans && Math.Abs(aMm - SegmentAMm) < 1e-9 && Math.Abs(lMm - SegmentLMm) < 1e-9;

    /// <summary>转换为引擎内部的 Check 记录。</summary>
    public List<MultiSpanStaticEngine.Check> ToChecks()
        => Checks.Select(c => new MultiSpanStaticEngine.Check(
                c.Group, c.Location, c.Computed, c.Allowable, c.Unit, c.RawLabel, c.RawAllowLabel))
            .ToList();

