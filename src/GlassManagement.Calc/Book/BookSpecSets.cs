    /// <summary>是否为 `AAA&lt;N&gt;.&lt;分组名&gt;：` 形式的分组标题行。</summary>
    public static bool IsGroupHeader(string line, out string title)
    {
        title = line;
        var i = line.IndexOf('.');
        if (i < 4 || i > 5 || !line.StartsWith("AAA") || !line.EndsWith("：")) return false;
        title = line.Substring(i + 1).TrimEnd('：');
        return true;
    }
