    /// <summary>按菜单路径解析窗体标题；未命中返回 null。</summary>
    public static string? Resolve(string top, string? sub)
    {
        if (!string.IsNullOrWhiteSpace(sub))
        {
            if (Exact.TryGetValue(top + "/" + sub, out var t1)) return t1;
            if (BySub.TryGetValue(sub, out var t2)) return t2;
        }
        return ByTop.TryGetValue(top, out var t3) ? t3 : null;
    }
